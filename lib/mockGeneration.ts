function pickOne<T>(items: T[]) {
  return items[Math.floor(Math.random() * items.length)];
}

export function generateMockInquiryReply({
  question,
  tone,
  inquiryType,
}: InquiryInput) {
  const checked = question.trim() ? "남겨주신 내용 확인했습니다." : "";
  return [
    pickOne(toneOpenings[tone]),
    checked,
    pickOne(inquiryCore[inquiryType]),
    pickOne(toneClosings[tone]),
  ]
    .filter(Boolean)
    .join(" ");
}

export function generateMockReviewReply({
  review,
  tone,
  reviewType,
}: ReviewInput) {
  const checked = review.trim() ? "남겨주신 리뷰 잘 확인했습니다." : "";
  return [
    pickOne(toneOpenings[tone]),
    checked,
    pickOne(reviewCore[reviewType][tone]),
  ]
    .filter(Boolean)
    .join(" ");
}

export function generateMockPromoPost({
  purpose,
  businessType,
  channel,
  extraNote = "",
}: PromoInput) {
  const note = extraNote.trim();
  const intro = pickOne(purposeCopy[purpose]);
  const businessLine = pickOne(businessCopy[businessType]);
  const noteCopy = note ? `\n\n오늘의 소식: ${note}` : "";
  const channelEnding = pickOne(channelEndings[channel]);

  if (channel === "인스타그램") {
    return `${intro}\n\n${businessLine}을 찾으신다면 오늘 편하게 들러주세요.${noteCopy}\n\n${channelEnding}`;
  }

  if (channel === "네이버 플레이스") {
    return `${intro} ${businessLine}을 준비하고 있습니다.${noteCopy}\n\n${channelEnding}`;
  }

  return `${intro}\n${businessLine}을 원하시면 편하게 메시지 주세요.${noteCopy}\n\n${channelEnding}`;
}
